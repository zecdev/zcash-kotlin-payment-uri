// ---------------------------------------------------------------------------
// Conformance corpus embedding (K1)
//
// The shared ZIP-321 vector corpus lives in the `test-vectors` git submodule
// as JSON files. `commonTest` runs on native targets that have neither a
// classloader nor a stable filesystem cwd, so instead of loading resources at
// runtime the task below embeds the raw JSON into a generated Kotlin source
// file (`GeneratedVectors.kt`) at build time. It also generates one
// `kotlin.test` function per corpus vector (`GeneratedZip321ConformanceTest.kt`)
// so per-vector granularity (names, counts, xfail reporting) is preserved on
// every target. Inputs/outputs are declared, so the sources regenerate
// whenever the submodule content changes.
// ---------------------------------------------------------------------------

val conformanceVectorsDir = rootProject.projectDir.resolve("test-vectors/vectors")

val generateConformanceVectors by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/conformance/kotlin")
    inputs.dir(conformanceVectorsDir)
    outputs.dir(outputDir)

    doLast {
        fun escapeForKotlin(text: String): String =
            buildString(text.length + 64) {
                for (ch in text) {
                    when (ch) {
                        '\\' -> append("\\\\")
                        '"' -> append("\\\"")
                        '$' -> append("\\$")
                        '\n' -> append("\\n")
                        '\r' -> append("\\r")
                        '\t' -> append("\\t")
                        else ->
                            if (ch.code < 0x20) {
                                append("\\u").append(ch.code.toString(16).padStart(4, '0'))
                            } else {
                                append(ch)
                            }
                    }
                }
            }

        val packageDir = outputDir.get().asFile.resolve("org/zecdev/zip321/conformance")
        packageDir.mkdirs()

        // Corpus JSON files, keyed by "<valid|invalid>/<file name>", in
        // deterministic name order.
        val jsonFiles =
            listOf("valid", "invalid").flatMap { dir ->
                conformanceVectorsDir.resolve(dir)
                    .listFiles { file -> file.name.endsWith(".json") }
                    .orEmpty()
                    .sortedBy { it.name }
                    .map { "$dir/${it.name}" to it }
            }
        check(jsonFiles.isNotEmpty()) {
            "No corpus JSON found under $conformanceVectorsDir. " +
                "Did you run `git submodule update --init`?"
        }

        packageDir.resolve("GeneratedVectors.kt").writeText(
            buildString {
                appendLine("// GENERATED by the `generateConformanceVectors` Gradle task — DO NOT EDIT.")
                appendLine("// Source of truth: test-vectors/vectors/**/*.json (git submodule).")
                appendLine("package org.zecdev.zip321.conformance")
                appendLine()
                appendLine("internal object GeneratedVectors {")
                appendLine("    val files: Map<String, String> = mapOf(")
                jsonFiles.forEachIndexed { i, (key, file) ->
                    val separator = if (i == jsonFiles.size - 1) "" else ","
                    appendLine("        \"$key\" to \"${escapeForKotlin(file.readText())}\"$separator")
                }
                appendLine("    )")
                appendLine("}")
            },
        )

        // One kotlin.test function per vector, mirroring the three phases of
        // the pre-K1 kotest runner. Render tests are only generated for
        // vectors that carry a canonical URI (currently all of them).
        val slurper = groovy.json.JsonSlurper()

        fun vectorsIn(dir: String): List<Map<*, *>> =
            jsonFiles
                .filter { (key, _) -> key.startsWith("$dir/") }
                .flatMap { (_, file) ->
                    @Suppress("UNCHECKED_CAST")
                    (slurper.parse(file) as List<Map<*, *>>)
                }
        val validVectors = vectorsIn("valid")
        val invalidVectors = vectorsIn("invalid")

        packageDir.resolve("GeneratedZip321ConformanceTest.kt").writeText(
            buildString {
                appendLine("// GENERATED by the `generateConformanceVectors` Gradle task — DO NOT EDIT.")
                appendLine("// One test per corpus vector; assertions live in ConformanceRunner.kt.")
                appendLine("package org.zecdev.zip321.conformance")
                appendLine()
                appendLine("import kotlin.test.Test")
                appendLine()
                appendLine("class GeneratedZip321ConformanceTest {")
                validVectors.forEach { vector ->
                    val name = vector["name"] as String
                    appendLine()
                    appendLine("    @Test")
                    appendLine("    fun `valid vector parses to the reference payments - $name`() {")
                    appendLine("        ConformanceRunner.checkValid(\"$name\")")
                    appendLine("    }")
                    if (vector["canonicalUri"] != null) {
                        appendLine()
                        appendLine("    @Test")
                        appendLine("    fun `valid vector re-renders to the reference canonical URI - $name`() {")
                        appendLine("        ConformanceRunner.checkRender(\"$name\")")
                        appendLine("    }")
                    }
                }
                invalidVectors.forEach { vector ->
                    val name = vector["name"] as String
                    appendLine()
                    appendLine("    @Test")
                    appendLine("    fun `invalid vector is rejected with a ZIP321 Errors - $name`() {")
                    appendLine("        ConformanceRunner.checkInvalid(\"$name\")")
                    appendLine("    }")
                }
                appendLine("}")
            },
        )
    }
}

